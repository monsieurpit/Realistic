/* Builds dist/PatOS.html: the whole OS (including three.js) in ONE file.
   Use it as a Claude Artifact, or download it and open it on a Chromebook with no internet. */
const fs = require('fs');
const path = require('path');
const root = __dirname;
// the version number and release notes, from updates.json (newest first)
{
  // a release with a "beta" number is still being put together: only people with Beta updates on are told about it
  const all = JSON.parse(fs.readFileSync(path.join(root, 'updates.json'), 'utf8'));
  const rel = all.filter((r) => !r.beta), beta = all.find((r) => r.beta) || null;
  fs.writeFileSync(path.join(root, 'js', 'version.js'), '/* generated by build.js from updates.json: do not edit */\nPatOS.version = ' + JSON.stringify(rel[0].version) + ';\nPatOS.releases = ' + JSON.stringify(rel) + ';\nPatOS.beta = ' + JSON.stringify(beta) + ';\n');
}
let html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
// inline stylesheets
html = html.replace(/<link rel="stylesheet" href="([^"]+)">/g, (_, href) => `<style>\n${read(href)}\n</style>`);
// inline scripts (escape any closing script tags inside the code)
html = html.replace(/<script( type="patos\/(?:js|3d)")? src="([^"]+)"><\/script>/g, (_, type, src) => `<script${type || ''}>\n${read(src).replace(/<\/script/gi, '<\\/script')}\n</script>`);
// inline the icon, drop the manifest (single-file mode)
const icon = 'data:image/svg+xml;base64,' + Buffer.from(read('assets/icon.svg')).toString('base64');
const touch = 'data:image/png;base64,' + fs.readFileSync(path.join(root, 'assets/icon-180.png')).toString('base64');
html = html.replace(/<link rel="apple-touch-icon"[^>]*>/, `<link rel="apple-touch-icon" href="${touch}">`);
html = html.replace(/<link rel="icon"[^>]*>/, `<link rel="icon" href="${icon}">`).replace(/<link rel="manifest"[^>]*>\n?/, '');
html = html.replace('<html lang="en" data-theme="dark">', '<html lang="en" data-theme="dark" data-single-file="1">');
html = html.replace('<link rel="stylesheet"', '<link rel="stylesheet"').replace('<body>', '<body>\n  <script>window.PATOS_SINGLE_FILE = 1;</script>');
fs.mkdirSync(path.join(root, 'dist'), { recursive: true });
fs.writeFileSync(path.join(root, 'dist', 'PatOS.html'), html);
console.log('Built dist/PatOS.html (' + (html.length / 1024 / 1024).toFixed(2) + ' MB)');

// Claude Artifact version: the artifact host adds its own <!doctype>/<html>/<head>/<body>, so emit just the contents.
const head = html.match(/<head>([\s\S]*?)<\/head>/)[1].replace(/<meta charset[^>]*>\s*/, '').replace(/<meta name="viewport"[^>]*>\s*/, '');
const body = html.match(/<body>([\s\S]*)<\/body>/)[1];
const art = head.trim() + '\n<style>html,body{height:100%;margin:0;overflow:hidden}</style>\n' + body.trim() + '\n';
fs.writeFileSync(path.join(root, 'dist', 'artifact.html'), art);
console.log('Built dist/artifact.html (' + (art.length / 1024 / 1024).toFixed(2) + ' MB)');

// Offline support: a service worker that stores every PatOS file on the device the first time it loads.
const assets = ['./', 'index.html', 'manifest.webmanifest', 'assets/icon.svg', 'assets/icon-180.png', 'assets/icon-192.png', 'assets/icon-512.png', 'assets/icon-maskable-512.png'];
read('index.html').replace(/(?:src|href)="((?:css|js|vendor)\/[^"]+)"/g, (_, p) => { assets.push(p); return _; });
const version = require('crypto').createHash('sha1').update(assets.map((a) => (a === './' ? '' : fs.readFileSync(path.join(root, a)))).join('')).digest('hex').slice(0, 10);
fs.writeFileSync(path.join(root, 'sw.js'), `/* PatOS service worker (generated by build.js): keeps PatOS working offline once it has loaded */
const CACHE = 'patos-${version}';
const FILES = ${JSON.stringify(assets, null, 0)};
self.addEventListener('install', (e) => { e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting())); });
// Update safety: the version that was running before stays on the device ("previous"). If the new one
// doesn't start, PatOS asks to go back to it (see js/preload.js), and Settings › This Device can too.
const META = 'patos-data-meta';
let meta = null;
const loadMeta = async () => { try { const r = await (await caches.open(META)).match('/__patos/meta'); meta = r ? await r.json() : {}; } catch (e) { meta = {}; } return meta; };
const saveMeta = async (m) => { meta = m; await (await caches.open(META)).put('/__patos/meta', new Response(JSON.stringify(m), { headers: { 'Content-Type': 'application/json' } })); };
const metaReady = loadMeta();
const isData = (k) => k.startsWith('patos-data-');
self.addEventListener('activate', (e) => { e.waitUntil((async () => {
  const m = await loadMeta(); const keys = await caches.keys();
  const versions = keys.filter((k) => k.startsWith('patos-') && !isData(k));
  // the previous version is the one that was running; the first time, any older copy that is still here
  let previous = m.current && m.current !== CACHE ? m.current : (m.current === CACHE ? m.previous : versions.find((k) => k !== CACHE));
  if (previous && !versions.includes(previous)) previous = null;
  const hadOld = !!versions.find((k) => k !== CACHE);
  await Promise.all(versions.filter((k) => k !== CACHE && k !== previous).map((k) => caches.delete(k)));
  // a new version always gets its chance, even after going back from an earlier one
  await saveMeta({ current: CACHE, previous: previous || null, useOld: m.current === CACHE ? !!m.useOld : false, since: m.current === CACHE ? m.since : Date.now() });
  await self.clients.claim();
  if (hadOld && m.current !== CACHE) (await self.clients.matchAll()).forEach((c) => c.postMessage({ patosUpdate: true }));
})()); });
// buttons on PatOS's Chrome notifications (Stop, Snooze): tell the open PatOS, or open it
self.addEventListener('notificationclick', (e) => {
  const n = e.notification; const d = n.data || {}; const action = e.action || 'open'; n.close();
  e.waitUntil((async () => {
    const cs = await self.clients.matchAll({ type: 'window', includeUncontrolled: true });
    if (cs.length) { cs.forEach((c) => c.postMessage({ patosNotif: true, id: d.id, action })); if (action === 'open') { try { await cs[0].focus(); } catch (er) {} } }
    else if (action === 'open' && self.clients.openWindow) await self.clients.openWindow('./');
  })());
});
// input() for Python: the Python worker waits on /__stdin/<run id> until PatOS sends it a line
const stdin = {};
self.addEventListener('message', (e) => {
  const d = e.data; if (!d) return;
  if (d.patosStdin) { const st = stdin[d.id] = stdin[d.id] || { q: [], w: [] }; if (st.w.length) st.w.shift()(d.text); else st.q.push(d.text); return; }
  const reply = (x) => { if (e.ports && e.ports[0]) e.ports[0].postMessage(x); };
  if (d.patosVersion || d.patosRollback || d.patosUseNewest) e.waitUntil((async () => {
    const m = Object.assign({}, await loadMeta());
    if (d.patosRollback) { if (!m.previous || !(await caches.has(m.previous))) return reply({ ok: false, reason: 'none' }); m.useOld = true; await saveMeta(m); }
    if (d.patosUseNewest) { m.useOld = false; await saveMeta(m); }
    reply(Object.assign({ ok: true, running: m.useOld && m.previous ? m.previous : CACHE, newest: CACHE }, m));
  })());
});
self.addEventListener('fetch', (e) => {
  const url = new URL(e.request.url);
  if (url.pathname.startsWith('/__stdin/')) {
    e.respondWith(new Promise((res) => { const id = url.pathname.split('/')[2]; const st = stdin[id] = stdin[id] || { q: [], w: [] }; const ans = (t) => res(t == null ? new Response('', { status: 204 }) : new Response(t)); if (st.q.length) ans(st.q.shift()); else st.w.push(ans); }));
    return;
  }
  if (e.request.method !== 'GET' || url.origin !== location.origin || url.pathname.startsWith('/api/')) return;
  // Python's files never change for a given version, so they are kept apart and survive PatOS updates
  if (url.pathname.startsWith('/pyodide/') || url.pathname.startsWith('/vendor/pdf/')) {
    // the PDF tools are fetched the first time a PDF is opened; the cache name carries their version
    e.respondWith(caches.open(url.pathname.startsWith('/pyodide/') ? 'patos-data-pyodide' : 'patos-data-pdf-3.11.174').then((c) => c.match(e.request, { ignoreSearch: true }).then((m) => m || fetch(e.request).then((r) => { if (r.ok && r.status === 200) c.put(e.request, r.clone()); return r; }))));
    return;
  }
  // saved copy first: PatOS opens instantly and works offline. A new version is picked up the next time PatOS loads.
  // Files come from one version only (the newest, or the previous one after going back), never a mix.
  e.respondWith((async () => {
    const m = meta || await metaReady;
    const name = m && m.useOld && m.previous ? m.previous : CACHE;
    const c = await caches.open(name);
    const hit = await c.match(e.request, { ignoreSearch: true });
    if (hit) return hit;
    try { const r = await fetch(e.request); if (r.ok && name === CACHE) c.put(e.request, r.clone()); return r; }
    catch (er) { return (await c.match('index.html')) || (await caches.match('index.html')) || Response.error(); }
  })());
});
`);
console.log('Wrote sw.js (' + assets.length + ' files, version ' + version + ')');
